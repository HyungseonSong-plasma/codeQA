"""Join B8's measured pipeline edges into a bounded, source-linked review ledger.

This is a *review worklist*, not a classifier of correct semantic ownership.
In particular, a sampled call is not evidence that an import or API is safe
to relocate, and a missing sampled call is not evidence of dead code.
"""
from __future__ import annotations

from collections import Counter
from collections.abc import Mapping
from hashlib import sha256
import json
from typing import Any


class EdgeReviewWorklistError(ValueError):
    """Cross-report source identity, denominator, or evidence is inconsistent."""


def _digest(value: Any) -> str:
    return sha256(json.dumps(value, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def _sealed(report: Mapping[str, Any], key: str) -> bool:
    return report[key] == _digest({k: v for k, v in report.items() if k != key})


def build_edge_review_worklist(
    responsibility: Mapping[str, Any],
    test_candidates: Mapping[str, Any],
    callsite_context: Mapping[str, Any],
    disposition: Mapping[str, Any],
) -> dict[str, Any]:
    """Correlate all measured pairs, preserving unknowns and collision gates.

    All four inputs must describe one exact source snapshot. No question is
    seeded and no candidate layout is generated by this read-only join.
    """
    try:
        reports = (
            (responsibility, "responsibility_id"),
            (test_candidates, "candidate_id"),
            (callsite_context, "context_id"),
            (disposition, "disposition_id"),
        )
        if any(r["schema_version"] != "0.1" or not _sealed(r, key)
               or r["decision"] != "NOT_EVALUATED" for r, key in reports):
            raise EdgeReviewWorklistError("invalid or unsealed input")
        rid = responsibility["responsibility_id"]
        identity = responsibility["source_identity"]
        head = identity["snapshot_sha"]
        for report in (test_candidates, callsite_context, disposition):
            source = report["source_identity"]
            if (source["snapshot_sha"] != head
                    or source["inventory_id"] != identity["inventory_id"]
                    or source["responsibility_id"] != rid):
                raise EdgeReviewWorklistError("mixed source identity")
        if (disposition["source_identity"]["triage_id"] != identity["triage_id"]
                or disposition["current_action"] != "NO_AUTOMATIC_MOVE"
                or responsibility["semantic_ownership"] != "NOT_EVALUATED"
                or test_candidates["observed_cross_role_pairs"]
                   != responsibility["observed_cross_role_pairs"]
                or callsite_context["static_pairs"]
                   != responsibility["observed_cross_role_pairs"]
                or callsite_context["semantic_ownership"] != "NOT_EVALUATED"
                or callsite_context["intentional_orchestration"] != "NOT_EVALUATED"):
            raise EdgeReviewWorklistError("incompatible review scope")

        def index_edges(report: Mapping[str, Any]) -> dict[tuple[str, str], dict[str, Any]]:
            result = {}
            for edge in report["edges"]:
                key = (edge["source_path"], edge["target_path"])
                if key in result:
                    raise EdgeReviewWorklistError("duplicate measured edge")
                result[key] = edge
            return result

        measured = index_edges(responsibility)
        tests = index_edges(test_candidates)
        contexts = index_edges(callsite_context)
        if (len(measured) != responsibility["observed_cross_role_pairs"]
                or set(measured) != set(tests) or set(measured) != set(contexts)):
            raise EdgeReviewWorklistError("incomplete measured pair join")
        dispositions = {s["signal_id"]: s for s in disposition["signal_dispositions"]}
        if (len(dispositions) != len(disposition["signal_dispositions"])
                or {e["signal_id"] for e in measured.values()} != set(dispositions)):
            raise EdgeReviewWorklistError("missing or duplicate signal disposition")

        rows = []
        for (src, dst), edge in sorted(measured.items()):
            test = tests[(src, dst)]
            ctx = contexts[(src, dst)]
            if (test["signal_id"] != edge["signal_id"]
                    or ctx["source_role"] != edge["source_role"]
                    or ctx["target_role"] != edge["target_role"]
                    or ctx["declared_policy_direction"] != edge["declared_policy_direction"]
                    or ctx["source_sha256"] != edge["import_witnesses"][0]["source_sha256"]
                    or ctx["semantic_ownership"] != "NOT_EVALUATED"
                    or test["behavioral_edge_coverage"] != "NOT_EVALUATED"
                    or not edge["import_witnesses"]
                    or any(w["source_path"] != src or w["target_path"] != dst
                           or w["source_sha256"] != ctx["source_sha256"]
                           or type(w["line"]) is not int or w["line"] < 1
                           for w in edge["import_witnesses"])):
                raise EdgeReviewWorklistError("edge provenance or policy mismatch")
            sites = test["candidate_test_paths"]
            test_functions = sum(len(site["candidate_tests"]) for site in sites)
            assertion_operand_pairs = sum(
                len(t["assertion_operand_pairs"])
                for site in sites for t in site["candidate_tests"]
            )
            witnesses = ctx["sampled_call_witnesses"]
            calls = ctx["direct_python_calls"]
            if (type(calls) is not int or calls < 0
                    or len(witnesses) > calls
                    or ctx["witnesses_truncated"] is not (calls > len(witnesses))
                    or any(site["parse_status"] not in (
                        "PARSED", "PARSE_FAILED", "DECODE_FAILED"
                    ) for site in sites)):
                raise EdgeReviewWorklistError("untrustworthy call/test denominator")
            alias = sum(bool(w["target_import_alias_call_candidates"]) for w in witnesses)
            shadow = sum(bool(
                w["target_import_alias_parameter_shadowing_warnings"]
                or w["target_import_alias_local_binding_warnings"]
            ) for w in witnesses)
            indirect = sum(bool(w["unmatched_indirect_receiver_call_candidates"])
                           and not w["target_import_alias_call_candidates"]
                           for w in witnesses)
            if edge["declared_policy_direction"] != "DECLARED_ALLOWED":
                focus = "DECLARED_BOUNDARY_REVIEW"
            elif shadow:
                focus = "ALIAS_BINDING_REVIEW"
            elif calls:
                focus = "OBSERVED_CALLSITE_REVIEW"
            else:
                focus = "UNOBSERVED_IN_BOUNDED_SAMPLE"
            rows.append({
                "signal_id": edge["signal_id"],
                "source_path": src,
                "target_path": dst,
                "source_role": edge["source_role"],
                "target_role": edge["target_role"],
                "declared_policy_direction": edge["declared_policy_direction"],
                "import_witnesses": edge["import_witnesses"],
                "direct_python_calls": calls,
                "sampled_call_witnesses": len(witnesses),
                "sampled_alias_call_candidates": alias,
                "sampled_shadowing_warnings": shadow,
                "sampled_indirect_receiver_candidates": indirect,
                "callsite_examples": [{
                    "test_id": w["test_id"],
                    "caller_line": w["caller_line"],
                    "function_qualname": w["function_qualname"],
                    "enclosing_statement_kind": w["enclosing_statement_kind"],
                } for w in witnesses[:5]],
                "candidate_test_functions": test_functions,
                "assertion_operand_candidates": assertion_operand_pairs,
                "candidate_test_paths": [site["test_path"] for site in sites],
                "review_focus": focus,
                "signal_disposition": dispositions[edge["signal_id"]]["disposition"],
                "semantic_ownership": "NOT_EVALUATED",
                "behavioral_edge_coverage": "NOT_EVALUATED",
                "external_consumers": "NOT_EVALUATED",
                "public_api_compatibility": "NOT_EVALUATED",
                "recommended_action": "NO_AUTOMATIC_MOVE",
            })
        if (sum(r["direct_python_calls"] for r in rows)
                != callsite_context["direct_python_calls"]
                or sum(r["sampled_call_witnesses"] for r in rows)
                   != callsite_context["sampled_call_witnesses"]
                or sum(r["candidate_test_functions"] for r in rows)
                   != test_candidates["candidate_test_functions_across_edges"]
                or sum(r["assertion_operand_candidates"] for r in rows)
                   != test_candidates["assertion_operand_candidate_pairs_across_edges"]
                or sum(r["direct_python_calls"] > 0 for r in rows)
                   != callsite_context["direct_call_observed_pairs"]):
            raise EdgeReviewWorklistError("cross-report count mismatch")
        focus_counts = Counter(row["review_focus"] for row in rows)
        result = {
            "schema_version": "0.1",
            "source_identity": {
                "snapshot_sha": head,
                "responsibility_id": rid,
                "candidate_id": test_candidates["candidate_id"],
                "context_id": callsite_context["context_id"],
                "disposition_id": disposition["disposition_id"],
            },
            "observed_cross_role_pairs": len(rows),
            "review_focus_counts": dict(sorted(focus_counts.items())),
            "edges": rows,
            "decision": "NOT_EVALUATED",
            "semantic_ownership": "NOT_EVALUATED",
            "recommended_action": "NO_AUTOMATIC_MOVE",
            "limitations": [
                "review focus is evidence triage, not a verdict on orchestration or misplaced ownership",
                "a direct sampled Python call does not prove import execution or intentional composition",
                "no sampled call does not prove a dead dependency",
                "test assertion proximity is not behavioral coverage of a downstream edge",
                "collision rejection is not a global KEEP decision",
                "external consumers, public API and semantic ownership remain NOT_EVALUATED",
            ],
        }
        result["worklist_id"] = _digest(result)
        return result
    except (KeyError, TypeError, AttributeError, ValueError) as exc:
        raise EdgeReviewWorklistError("untrustworthy edge review worklist inputs") from exc


def render_edge_review_worklist_markdown(report: Mapping[str, Any]) -> str:
    """Render every pair with source and bounded call/test evidence."""
    try:
        if (not _sealed(report, "worklist_id")
                or report["decision"] != "NOT_EVALUATED"
                or report["recommended_action"] != "NO_AUTOMATIC_MOVE"
                or len(report["edges"]) != report["observed_cross_role_pairs"]):
            raise EdgeReviewWorklistError("modified worklist")
        lines = [
            "## Measured edge responsibility review worklist", "",
            "Source HEAD: " + report["source_identity"]["snapshot_sha"],
            "Cross-role pairs: " + str(report["observed_cross_role_pairs"]),
            "Review focus is not a semantic ownership verdict; no automatic move.",
        ]
        for row in report["edges"]:
            witness = row["import_witnesses"][0]
            lines.append(
                "- `" + row["source_path"] + ":" + str(witness["line"])
                + "` -> `" + row["target_path"] + "` ["
                + row["review_focus"] + "; " + row["declared_policy_direction"]
                + "; calls=" + str(row["direct_python_calls"])
                + "; sampled-sites=" + str(row["sampled_call_witnesses"])
                + "; test-candidates=" + str(row["candidate_test_functions"])
                + "; assertion-operand-candidates=" + str(row["assertion_operand_candidates"])
                + "; signal=" + row["signal_disposition"] + "]"
            )
        lines.extend(["",
            "Source-linked call and test candidates do not establish correct ownership.",
            "External consumers, public API and behavioral edge coverage: NOT_EVALUATED.", "",
        ])
        return "\n".join(lines)
    except (KeyError, TypeError, AttributeError, ValueError) as exc:
        raise EdgeReviewWorklistError("untrustworthy edge review worklist report") from exc
